import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { chromium } from 'playwright'
import { designReviewPath, signInDemo } from './browser-helpers.mjs'

const baseURL = process.env.AURA_TEST_URL ?? 'http://127.0.0.1:5173'
const output = designReviewPath('assessment-intro')
await mkdir(output, { recursive: true })
const browser = await chromium.launch({
  executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || undefined,
})

try {
  for (const [width, height] of [[1440, 900], [390, 844], [320, 640]]) {
    const page = await browser.newPage({ viewport: { width, height }, reducedMotion: 'no-preference' })
    await signInDemo(page, baseURL)
    async function navigate(name) {
      if (width <= 760) await page.getByRole('button', { name: 'Open navigation' }).click()
      await page.locator('.sidebar').getByRole('link', { name, exact: true }).click()
    }
    await navigate('Assessments')
    const header = page.locator('.app-header--assessment')
    await header.waitFor()
    const headerHeight = (await header.boundingBox()).height
    assert(headerHeight <= 76, 'Language selection uses the compact assessment header')
    assert.equal(await header.locator('.header-assessment').count(), 0)
    await page.clock.install()
    await page.clock.pauseAt(new Date(Date.now() + 1000))
    await page.getByRole('radio', { name: 'English', exact: true }).check()
    await page.getByRole('button', { name: 'Start pre-assessment', exact: true }).evaluate((button) => {
      button.click()
      button.click()
    })
    const input = page.getByLabel('Your response')
    assert(await input.isVisible())
    assert.equal(await input.getAttribute('placeholder'), 'Type your response...')
    assert.equal(await page.locator('.message').count(), 0)
    await page.clock.runFor(250)
    assert.equal(await page.locator('.message').count(), 0)
    await page.screenshot({ path: `${output}/opening-${width}.png` })
    await page.clock.runFor(250)
    await page.locator('.message--typing').waitFor()
    assert.equal((await header.boundingBox()).height, headerHeight, 'Header stays compact during the questionnaire')
    assert.equal(await page.locator('.message--typing .message-avatar').count(), 1)
    assert.equal(await page.locator('.message--typing .typing > span:not(.sr-only)').count(), 3)
    assert.equal(await page.getByRole('button', { name: 'Sometimes', exact: true }).count(), 0)
    assert.equal(await page.getByRole('log').getAttribute('aria-busy'), 'true')
    const thinkingBox = await page.locator('.message--typing').boundingBox()
    const composerBox = await page.locator('.chat-input').boundingBox()
    assert(thinkingBox.y + thinkingBox.height <= composerBox.y, 'Thinking stays above the composer')
    assert(composerBox.y - thinkingBox.y - thinkingBox.height < 60, 'Thinking starts near the bottom input')
    await page.screenshot({ path: `${output}/thinking-${width}.png` })
    await page.clock.runFor(1000)
    await page.locator('.chat-typing-cursor').waitFor()
    await page.clock.runFor(160)
    assert((await page.locator('.message-bubble p').first().innerText()).length < 85)
    assert(await input.isDisabled())
    assert.equal(await page.getByRole('button', { name: 'Sometimes', exact: true }).count(), 0)
    const greetingBox = await page.locator('.message').first().boundingBox()
    await page.clock.runFor(10000)
    const choice = page.getByRole('button', { name: 'Sometimes', exact: true })
    await choice.waitFor()
    assert(await choice.isEnabled())
    assert.equal(await page.getByRole('log').getAttribute('aria-busy'), 'false')
    assert((await page.locator('.message').first().boundingBox()).y < greetingBox.y, 'Question and choices push the greeting upward')
    const log = page.getByRole('log')
    if (await log.evaluate((element) => element.scrollHeight > element.clientHeight)) {
      await log.evaluate((element) => { element.scrollTop = 0 })
      const firstMessage = await page.locator('.message').first().boundingBox()
      const logBox = await log.boundingBox()
      assert(firstMessage.y >= logBox.y - 1, 'Earlier messages remain reachable when content overflows')
      await log.evaluate((element) => { element.scrollTop = element.scrollHeight })
    }
    await page.screenshot({ path: `${output}/question-${width}.png` })
    await choice.evaluate((button) => { button.click(); button.click() })
    assert(await input.isVisible())
    assert.equal(await page.locator('.question-message').count(), 1, 'Question stays visible after selecting an answer')
    assert.equal(await page.locator('.structured-response').getByText('Sometimes', { exact: true }).count(), 1, 'Selected answer appears immediately')
    await page.clock.runFor(500)
    await page.locator('.message--typing').waitFor()
    assert.equal(await page.locator('.message--typing .message-avatar').count(), 1)
    assert.equal(await page.locator('.message--typing .typing > span:not(.sr-only)').count(), 3)
    const followThinking = await page.locator('.message--typing').boundingBox()
    const followComposer = await page.locator('.chat-input').boundingBox()
    assert(followComposer.y - followThinking.y - followThinking.height < 60, 'Follow-up thinking also starts at the bottom')
    assert(await input.isDisabled())
    await page.clock.runFor(1000)
    await page.locator('.follow-up-message .chat-typing-cursor').waitFor()
    assert(await input.isDisabled())
    await page.clock.runFor(10000)
    assert(await input.isEnabled())
    assert.equal(await page.getByRole('progressbar').getAttribute('value'), '1')
    assert.equal(await page.locator('.message--typing,.chat-typing-cursor').count(), 0)
    await page.screenshot({ path: `${output}/follow-up-${width}.png` })
    const observation = 'A fictional observation for the animated assessment.'
    await input.fill(observation)
    await input.press('Enter')
    await page.getByText(observation, { exact: true }).waitFor()
    assert.equal(await page.getByRole('button', { name: /Next question|Finish assessment/ }).count(), 0)
    for (let attempt = 0; attempt < 40 && await page.locator('.question-message .chat-typing-cursor').count() === 0; attempt += 1)
      await page.clock.runFor(100)
    await page.locator('.question-message .chat-typing-cursor').waitFor()
    assert.equal(await page.locator('.question-message').count(), 2)
    assert.equal(await page.locator('.follow-up-message').count(), 1)
    assert.equal(await page.locator('.structured-response').count(), 1)
    assert.equal(await page.getByText(observation, { exact: true }).count(), 1)
    await log.evaluate((element) => { element.scrollTop = 0; element.dispatchEvent(new Event('scroll')) })
    await page.clock.runFor(10000)
    assert.equal(await log.evaluate((element) => element.scrollTop), 0, 'Typing does not pull a reader away from older messages')
    const oldQuestion = await page.locator('.question-message').first().boundingBox()
    const logPosition = await log.boundingBox()
    assert(oldQuestion.y >= logPosition.y && oldQuestion.y < logPosition.y + logPosition.height)
    await page.screenshot({ path: `${output}/scroll-back-${width}.png` })
    await log.evaluate((element) => { element.scrollTop = element.scrollHeight; element.dispatchEvent(new Event('scroll')) })
    await page.getByRole('heading', { name: 'Question 2 of 13: Eye Contact' }).waitFor()
    assert(await page.getByRole('button', { name: 'Always', exact: true }).isEnabled())
    await navigate('Chat')
    await navigate('Assessments')
    await page.getByRole('heading', { name: 'Question 2 of 13: Eye Contact' }).waitFor()
    assert.equal(await page.locator('.message--typing,.chat-typing-cursor').count(), 0)
    assert.equal(await page.getByText(observation, { exact: true }).count(), 1)
    assert.equal(await page.locator('.structured-response').count(), 1)
    assert.equal(await page.getByText(/Let.*begin the pre-assessment/).count(), 1, 'Initial greeting does not replay')
    const box = await page.locator('.chat-input').boundingBox()
    assert(box.y >= 0 && box.y + box.height <= height + 1)
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    assert.equal(await page.evaluate(() => localStorage.length + sessionStorage.length), 0)
    console.log(`${width}px: bottom-aligned thinking, upward-growing messages, overflow scrolling, typed intro/question/follow-up, automatic advancement, retained history, reading position and no replay passed.`)
    await page.close()
  }
  const reduced = await browser.newPage({ reducedMotion: 'reduce' })
  await signInDemo(reduced, baseURL)
  await reduced.getByRole('link', { name: 'Assessments', exact: true }).click()
  await reduced.getByRole('radio', { name: 'English', exact: true }).check()
  await reduced.getByRole('button', { name: 'Start pre-assessment', exact: true }).click()
  await reduced.getByRole('button', { name: 'Always', exact: true }).click()
  await reduced.getByLabel('Your response').waitFor({ state: 'visible' })
  await reduced.waitForFunction(() => !document.querySelector('#chat-response').disabled)
  assert.equal(await reduced.locator('.chat-typing-cursor').count(), 0)
  assert((await reduced.locator('.follow-up-message p').innerText()).includes('Please describe'))
  await reduced.evaluate(async () => {
    const { assessmentService } = await import('/src/services/api/assessmentService.ts')
    const original = assessmentService.nextQuestion
    assessmentService.nextQuestion = async () => {
      assessmentService.nextQuestion = original
      throw new Error('Simulated next-question failure')
    }
  })
  const retainedResponse = 'A fictional response retained after a failed transition.'
  await reduced.getByLabel('Your response').fill(retainedResponse)
  await reduced.getByLabel('Your response').press('Enter')
  await reduced.getByRole('alert').getByText('Simulated next-question failure').waitFor()
  assert.equal(await reduced.getByText(retainedResponse, { exact: true }).count(), 1)
  await reduced.getByRole('button', { name: 'Retry', exact: true }).click()
  await reduced.getByRole('heading', { name: 'Question 2 of 13: Eye Contact' }).waitFor()
  assert.equal(await reduced.getByText(retainedResponse, { exact: true }).count(), 1)
  assert.equal(await reduced.locator('.structured-response').count(), 1)
  assert.equal(await reduced.getByRole('button', { name: /Next question|Finish assessment|Retry/ }).count(), 0)
  console.log('Reduced motion and failed-transition retry passed; original answer stays saved once.')
  await reduced.close()
} finally {
  await browser.close()
}
